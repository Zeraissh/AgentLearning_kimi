"""练习 6：切片。

任务：定义列表 nums = list(range(1, 21))（即 1 到 20），用切片完成：
    1. 取前 3 个元素
    2. 取后 3 个元素
    3. 取中间一段（第 8 到第 12 个元素）
    4. 反转整个列表（步长为负）
    5. 取所有偶数位置的元素（步长为 2，想清楚从哪个下标开始）

提示：切片是左闭右开区间，nums[0:3] 含下标 0 但不含下标 3
"""

# 在下面写你的代码：
nums :list[int] = list(range(1, 21))
print("前三个元素:", nums[0:3])
print("后三个元素:", nums[-3:])
print("中间一段（第 8 到第 12 个元素）:", nums[7:12])
print("反转整个列表:", nums[::-1])
print("所有偶数位置的元素:", nums[0::2])
